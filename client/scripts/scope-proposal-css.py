"""Builds client/src/styles/proposal.css from the approved proposal's CSS (proto.css + round3.css), unchanged
except that every rule is scoped under `.pz` (the menu screens' root), so it never touches the in-game HUD.
Run it again whenever the proposal CSS changes:  python client/scripts/scope-proposal-css.py
"""
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = [ROOT / '.impeccable/mocks/propuesta/proto.css', ROOT / '.impeccable/mocks/propuesta/round3.css']
OUT = ROOT / 'src/styles/proposal.css'
KEYFRAMES = ('in', 'pop', 'flash')


def scope_selector(sel: str) -> str:
    sel = sel.strip()
    if sel in (':root', 'html', 'body'):
        return '.pz'
    if sel in ('*', '*::before', '*::after'):
        return '.pz' + sel[1:] + ', .pz ' + sel
    if sel.startswith('[data-font'):
        return '.pz' + sel
    return '.pz ' + sel


def scope_rules(css: str) -> str:
    out, i = [], 0
    while i < len(css):
        j = css.find('{', i)
        if j < 0:
            out.append(css[i:])
            break
        head = css[i:j]
        # Comments before the selector stay as they are
        lead = ''
        while '*/' in head:
            k = head.index('*/') + 2
            lead += head[:k]
            head = head[k:]
        sel = head.strip()
        if sel.startswith('@media') or sel.startswith('@supports'):
            depth, k = 1, j + 1
            while depth:
                depth += {'{': 1, '}': -1}.get(css[k], 0)
                k += 1
            out.append(lead + head + '{' + scope_rules(css[j + 1:k - 1]) + '}')
            i = k
            continue
        k = css.index('}', j)
        body = css[j:k + 1]
        if sel.startswith('@keyframes') or sel.startswith('@property') or sel.startswith('@font-face'):
            if sel.startswith('@keyframes'):
                # keyframes are nested: copy until the matching brace
                depth, k = 1, j + 1
                while depth:
                    depth += {'{': 1, '}': -1}.get(css[k], 0)
                    k += 1
                body = css[j:k]
                k -= 1
                name = sel.split()[1]
                head = head.replace(name, 'pz-' + name)
            out.append(lead + head + body)
        else:
            scoped = ',\n'.join(scope_selector(s) for s in sel.split(','))
            out.append(lead + head[: len(head) - len(head.lstrip())] + scoped + ' ' + body)
        i = k + 1
    return ''.join(out)


css = '\n'.join(p.read_text(encoding='utf-8') for p in SRC)
css = scope_rules(css)
for name in KEYFRAMES:
    css = re.sub(rf'(animation:[^;]*?)\b{name}\b', rf'\1pz-{name}', css)
header = (
    '/* GENERATED by client/scripts/scope-proposal-css.py from the approved proposal\n'
    '   (.impeccable/mocks/propuesta/proto.css + round3.css). Do not edit: change the proposal and run the script.\n'
    '   Every rule is scoped under .pz, the root of the menu screens, so the in-game HUD keeps its own styles. */\n'
    '/* The proposal draws on <body>: the .pz root fills the window the same way. */\n'
    '.pz {\n  position: fixed;\n  inset: 0;\n  overflow: hidden;\n}\n'
    '/* rem follows the window like in the proposal (the HUD is in px and does not use rem) */\n'
    'html {\n  font-size: clamp(11px, min(1.11vw, 1.78vh), 20px);\n}\n'
)
OUT.write_text(header + css, encoding='utf-8')
# Keep the repo's formatting
subprocess.run('npx prettier --write src/styles/proposal.css', cwd=ROOT, check=True, shell=True)
print('wrote', OUT, len(css))
